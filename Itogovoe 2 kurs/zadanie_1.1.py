def fib_generator(n):
    """
    Генерирует последовательность Фибоначчи до n-го числа,
    выдавая по одному числу за раз с помощью yield.
    """
    a, b = 0, 1
    for _ in range(n):
        yield a
        a, b = b, a + b

# Пример использования
# Генератор сам по себе не хранит числа, его нужно обойти в цикле
print("Числа из генератора:")
for number in fib_generator(10):
    print(number, end=" ") # Выводим числа в одну строку

# Или можно превратить его в список, если это необходимо
print("\n\nГенератор, преобразованный в список:")
fib_sequence = list(fib_generator(10))
print(fib_sequence)